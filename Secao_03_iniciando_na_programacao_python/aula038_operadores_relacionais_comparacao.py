"""
    — Operadores de comparação:
        Os operadores de conmparação retornam um boolean.

        > ..... maior
        >= .... maior ou igual
        < ..... menor
        <= .... menor ou igual
        == .... igual
        != .... diferente

"""

print(2 > 1)
print(2 >= 2)

print(1 < 2)
print(2 <= 2)

print('a' == 'a')
print('a' != 'b')
