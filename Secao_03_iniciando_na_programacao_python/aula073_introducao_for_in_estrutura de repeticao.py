"""
    — for / in:
    
        O comando "for" em Python serve para repetir um bloco de código para cada item de uma sequência ou coleção de dados.

"""

nome = 'Erick'
lista_frutas = ['uva','morango','pêra','abacaxi','laranja']


# ************************************
# Iterando um string:

for letra in nome:
    print( letra)
    
print()


# ************************************
# Iterando uma lista:

for fruta in lista_frutas:
    print(fruta)

print()