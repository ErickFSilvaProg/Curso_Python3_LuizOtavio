"""
    Tipo primitivo string:

        str → string → texto
        Strings são textos que estão dentro de aspas, simples ou duplas.

    Tipagem do Python: Dinâmica e forte

"""


# Exemplo: Strings.
print('String', '1234', sep=' → ')
print()


# Aspas simples: String.
print('Erick Ferreira')


# Aspas duplas: String.
print('Erick Ferreira, "programador python".')


# Escape:
print('Erick Ferreira, \'programador Python\'.')


# r (expressões regulares):
print(r"Erick Ferreira, \"programador Python\".")