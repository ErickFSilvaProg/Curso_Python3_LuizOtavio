"""
    Tipos primitivos int e float

    O Python distingue os números com e sem casas decimais.
    

    — int: número inteiro

        O tipo int representa qualquer número positivo ou negativo.
        int sem o sinal negativo [-] é considerado positivo.
    
    — float: número com ponto flutuante

        O tipo float representa qualquer número positivo ou negativo com ponto flutuante.
        float sem o sinal negativo [-] é considerado positivo.
    
    A função "type()" mostra o tipo que o Python inferiu ao valor.
    
    Na programação o ponto [.] sempre será utilizado para separar as casas decimais de um número.
    
    Tudo em Python é um objeto.

"""


# Números inteiros:
print(11)
print(-11)
print(0)
print()


# Números float:
print(11.1)
print(0.0)
print(-1.1)
print()


# Função "type()": Identifica o tipo do valor.
print(type(10), 10)
print(type(0), 0)
print(type(-11))
print()

print(type(11.10), 11.10)
print(type(0.0), 0.0)
print(type(-1.1), -1.1)
print()